#!/usr/bin/env python3
"""Build the GitHub Pages deployable site for jacklinus.com.

index.html is the master copy of the full page -- this is the only file you
ever edit. This script splits it into:

  _site/index.html   -- a tiny shell. This is what "View Page Source" shows.
  _site/assets/desktop.js -- the real CSS, markup, and page logic, rebuilt
                            into the page the instant it loads.

Everything else (Photos/, CNAME, ads.txt, etc.) is copied into _site/ untouched.

Run:  python3 tools/build_site.py
"""
import json
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'index.html')
OUT = os.path.join(ROOT, '_site')

with open(SRC, encoding='utf-8') as f:
    html = f.read()

# --- head: keep metadata, replace the <style> block with a placeholder -------
head_end = html.index('</head>') + len('</head>')
head = html[:head_end]

css_match = re.search(r'<style\b[^>]*>(.*?)</style>', html, re.DOTALL | re.IGNORECASE)
if not css_match:
    sys.exit('no <style> block found in index.html')
css = css_match.group(1)

head = re.sub(r'<style\b[^>]*>.*?</style>',
              '<style id="rw-css"></style>',
              head, count=1, flags=re.DOTALL | re.IGNORECASE)

# --- body: markup + all <script> tags ---------------------------------------
body_start = html.index('<body>') + len('<body>')
body_end = html.index('</body>')
body_region = html[body_start:body_end]

script_re = re.compile(r'<script\b([^>]*)>(.*?)</script>',
                       re.DOTALL | re.IGNORECASE)

found = []
def strip_script(m):
    found.append((m.group(1), m.group(2)))
    return ''

markup = script_re.sub(strip_script, body_region)

if not found:
    sys.exit('no <script> found in <body>')

# Last script in the body is the page's own logic; everything before it
# (ad snippets, Firebase SDKs, ...) is recreated after the markup is injected.
page_script = found.pop()[1]
pre_scripts = found  # in document order

def attr(attrs, name):
    m = re.search(r'\b' + name + r'\s*=\s*["\']([^"\']*)["\']', attrs, re.IGNORECASE)
    return m.group(1) if m else None

js_lines = [
    '/* Jack Linus · Encrypted Chat — generated by tools/build_site.py */',
    '/* Edit index.html; GitHub Actions rebuilds this file on every publish. */',
    'var __rwCss = ' + json.dumps(css, ensure_ascii=False) + ';',
    'var __rwMarkup = ' + json.dumps(markup, ensure_ascii=False) + ';',
    '',
    '(function () {',
    "    var el = document.getElementById('rw-css');",
    "    if (!el) { el = document.createElement('style'); el.id = 'rw-css'; document.head.appendChild(el); }",
    "    el.textContent = __rwCss;",
    '    document.body.innerHTML = __rwMarkup;',
]

for attrs, text in pre_scripts:
    src = attr(attrs, 'src')
    typ = attr(attrs, 'type')
    js_lines.append("    var s=document.createElement('script');")
    if src:
        js_lines.append('    s.src=' + json.dumps(src, ensure_ascii=False) + ';')
        if re.search(r'\basync\b', attrs, re.IGNORECASE):
            js_lines.append('    s.async=true;')
        if re.search(r'\bdefer\b', attrs, re.IGNORECASE):
            js_lines.append('    s.defer=true;')
        if typ:
            js_lines.append('    s.type=' + json.dumps(typ, ensure_ascii=False) + ';')
        for extra in ('crossorigin', 'referrerpolicy', 'integrity', 'nonce'):
            v = attr(attrs, extra)
            if v:
                js_lines.append('    s.' + extra + '=' + json.dumps(v, ensure_ascii=False) + ';')
    else:
        js_lines.append('    s.textContent=' + json.dumps(text, ensure_ascii=False) + ';')
    js_lines.append('    document.body.appendChild(s);')

js_lines.append('})();')
js_lines.append('')
js_lines.append(page_script)
bundle = '\n'.join(js_lines) + '\n'

# --- shell ------------------------------------------------------------------
shell = head + '\n<body>\n<script src="assets/desktop.js"></script>\n</body>\n</html>\n'

# --- assemble _site ---------------------------------------------------------
if os.path.exists(OUT):
    shutil.rmtree(OUT)
shutil.copytree(ROOT, OUT, ignore=lambda d, names: [
    n for n in names if n in ('.git', '.github', 'index.html', '_site')
])

os.makedirs(os.path.join(OUT, 'assets'), exist_ok=True)
with open(os.path.join(OUT, 'index.html'), 'w', encoding='utf-8') as f:
    f.write(shell)
with open(os.path.join(OUT, 'assets', 'desktop.js'), 'w', encoding='utf-8') as f:
    f.write(bundle)

print('shell:   ' + os.path.join(OUT, 'index.html') +
      ' (%d bytes)' % len(shell.encode('utf-8')))
print('bundle:  ' + os.path.join(OUT, 'assets', 'desktop.js') +
      ' (%d bytes)' % len(bundle.encode('utf-8')))
print('master:  ' + SRC + ' (untouched)')
