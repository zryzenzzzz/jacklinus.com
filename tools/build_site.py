#!/usr/bin/env python3
"""Build the GitHub Pages deployable site for jacklinus.com.

index.html is the master copy of the full page -- this is the only file you
ever edit. This script splits it into:

  _site/index.html   -- a tiny shell. This is what "View Page Source" shows.
  _site/assets/desktop.js -- the real CSS, markup, and page logic, rebuilt
                            into the page the instant it loads.

Everything else (Photos/, CNAME, ads.txt, etc.) is copied into _site/ untouched.

Run:  python3 tools/build_site.py
"""
import json
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'index.html')
OUT = os.path.join(ROOT, '_site')

with open(SRC, encoding='utf-8') as f:
    html = f.read()

# --- head: keep metadata, replace the <style> block with a placeholder -------
head_end = html.index('</head>') + len('</head>')
head = html[:head_end]

css_match = re.search(r'<style\b[^>]*>(.*?)</style>', html, re.DOTALL | re.IGNORECASE)
if not css_match:
    sys.exit('no <style> block found in index.html')
css = css_match.group(1)

head = re.sub(r'<style\b[^>]*>.*?</style>',
              '<style id="rw-css"></style>',
              head, count=1, flags=re.DOTALL | re.IGNORECASE)

# --- body: markup + all <script> tags ---------------------------------------
body_start = html.index('<body>') + len('<body>')
body_end = html.index('</body>')
body_region = html[body_start:body_end]

script_re = re.compile(r'<script\b([^>]*)>(.*?)</script>',
                       re.DOTALL | re.IGNORECASE)

all_matches = list(script_re.finditer(body_region))
if not all_matches:
    sys.exit('no <script> found in <body>')

# Last script in the body is the page's own logic; everything before it
# (ad snippets, Firebase SDKs, ...) runs in the same order as the original HTML.
page_match = all_matches[-1]
page_script = page_match.group(2)
pre_matches = all_matches[:-1]

def attr(attrs, name):
    m = re.search(r'\b' + name + r'\s*=\s*["\']([^"\']*)["\']', attrs, re.IGNORECASE)
    return m.group(1) if m else None

# Categorize pre-page scripts:
#   Firebase scripts (src contains 'firebasejs') → load sequentially before page logic
#   All other scripts (ads, analytics) → replace with placeholder, re-add to parent container
firebase_scripts = []   # (attrs, text)
pre_scripts = []        # (attrs, text) — will use placeholder mechanism

script_counter = [0]
def replace_with_placeholder(m):
    # Page script: strip completely (handled separately)
    if m is page_match:
        return ''
    idx = script_counter[0]
    script_counter[0] += 1
    attrs, text = m.group(1), m.group(2)
    src = attr(attrs, 'src')
    if src and 'firebasejs' in src:
        firebase_scripts.append((attrs, text))
        return ''  # strip from markup, load sequentially
    pre_scripts.append((attrs, text))
    return '<div class="script-host" data-script-index="%d"></div>' % idx

markup = script_re.sub(replace_with_placeholder, body_region)

def attr(attrs, name):
    m = re.search(r'\b' + name + r'\s*=\s*["\']([^"\']*)["\']', attrs, re.IGNORECASE)
    return m.group(1) if m else None

js_lines = [
    '/* Jack Linus · Encrypted Chat — generated by tools/build_site.py */',
    '/* Edit index.html; GitHub Actions rebuilds this file on every publish. */',
    'var __rwCss = ' + json.dumps(css, ensure_ascii=False) + ';',
    'var __rwMarkup = ' + json.dumps(markup, ensure_ascii=False) + ';',
]

# Build __rwScripts array for placeholder-based scripts
if pre_scripts:
    js_lines.append('var __rwScripts = [' )
    for attrs, text in pre_scripts:
        src = attr(attrs, 'src')
        typ = attr(attrs, 'type')
        entry = '{src:' + json.dumps(src, ensure_ascii=False)
        entry += ', text:' + json.dumps(text, ensure_ascii=False)
        if typ:
            entry += ', type:' + json.dumps(typ, ensure_ascii=False)
        entry += '}'
        js_lines.append('    ' + entry + ',')
    js_lines.append('];')
else:
    js_lines.append('var __rwScripts = [];')

js_lines.append('')
js_lines.append('(function () {')
js_lines.append("    var el = document.getElementById('rw-css');")
js_lines.append("    if (!el) { el = document.createElement('style'); el.id = 'rw-css'; document.head.appendChild(el); }")
js_lines.append("    el.textContent = __rwCss;")
js_lines.append('    document.body.innerHTML = __rwMarkup;')

# --- Re-add placeholder scripts to their parent containers ------------------
js_lines.append('    var hosts = document.querySelectorAll(\'.script-host\');')
js_lines.append('    hosts.forEach(function (host) {')
js_lines.append('        var idx = host.getAttribute(\'data-script-index\');')
js_lines.append('        var info = __rwScripts[idx];')
js_lines.append('        var s = document.createElement(\'script\');')
js_lines.append('        if (info.src) { s.src = info.src; }')
js_lines.append('        if (info.type) { s.type = info.type; }')
js_lines.append('        if (info.async) { s.async = true; }')
js_lines.append('        if (info.defer) { s.defer = true; }')
js_lines.append('        if (!info.src) { s.textContent = info.text; }')
js_lines.append('        host.parentElement.appendChild(s);')
js_lines.append('        host.remove();')
js_lines.append('    });')

# --- Firebase scripts: load sequentially, then run page script --------------
if firebase_scripts:
    js_lines.append('    var _scripts = [')
    for attrs, text in firebase_scripts:
        src = attr(attrs, 'src')
        js_lines.append('        ' + json.dumps(src, ensure_ascii=False) + ',')
    js_lines.append('    ];')
    js_lines.append('    var _i = 0;')
    js_lines.append('    function _loadNext() {')
    js_lines.append('        if (_i >= _scripts.length) {')
    for line in page_script.splitlines():
        if line.strip():
            js_lines.append('            ' + line)
        else:
            js_lines.append('')
    js_lines.append('            return;')
    js_lines.append('        }')
    js_lines.append('        var s = document.createElement(\'script\');')
    js_lines.append('        s.src = _scripts[_i++];')
    js_lines.append('        s.onload = _loadNext;')
    js_lines.append('        s.onerror = _loadNext;')
    js_lines.append('        document.body.appendChild(s);')
    js_lines.append('    }')
    js_lines.append('    _loadNext();')
else:
    js_lines.append(page_script)

js_lines.append('})();')
bundle = '\n'.join(js_lines) + '\n'

# --- shell ------------------------------------------------------------------
shell = head + '\n<body>\n<script src="assets/desktop.js"></script>\n</body>\n</html>\n'

# --- assemble _site ---------------------------------------------------------
if os.path.exists(OUT):
    shutil.rmtree(OUT)
def ignore_func(d, names):
    # Only exclude root index.html (it's replaced by the shell);
    # subdirectory index.html files (Privacy/, terms/, etc.) must be kept.
    ignore_list = ['.git', '.github', '_site']
    if d == ROOT:
        ignore_list.append('index.html')
    return [n for n in names if n in ignore_list]


shutil.copytree(ROOT, OUT, ignore=ignore_func)

os.makedirs(os.path.join(OUT, 'assets'), exist_ok=True)
with open(os.path.join(OUT, 'index.html'), 'w', encoding='utf-8') as f:
    f.write(shell)
with open(os.path.join(OUT, 'assets', 'desktop.js'), 'w', encoding='utf-8') as f:
    f.write(bundle)

print('shell:   ' + os.path.join(OUT, 'index.html') +
      ' (%d bytes)' % len(shell.encode('utf-8')))
print('bundle:  ' + os.path.join(OUT, 'assets', 'desktop.js') +
      ' (%d bytes)' % len(bundle.encode('utf-8')))
print('master:  ' + SRC + ' (untouched)')
